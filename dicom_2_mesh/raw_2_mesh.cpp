XYZ VertexInterp(double isolevel, XYZ p1, XYZ p2, double valp1, double valp2)
{
    if (ABS(isolevel - valp1) < 0.00001) return p1;
    if (ABS(isolevel - valp2) < 0.00001) return p2;
    if (ABS(valp1 - valp2) < 0.00001) return p1;

    double mu = (isolevel - valp1) / (valp2 - valp1);

    XYZ p;
    p.x = p1.x + mu * (p2.x - p1.x);
    p.y = p1.y + mu * (p2.y - p1.y);
    p.z = p1.z + mu * (p2.z - p1.z);
    return p;
}

int Polygonise(GRIDCELL grid, double isolevel, TRIANGLE* triangles)
{
    int cubeindex = 0;

    if (grid.val[0] < isolevel) cubeindex |= 1;
    if (grid.val[1] < isolevel) cubeindex |= 2;
    if (grid.val[2] < isolevel) cubeindex |= 4;
    if (grid.val[3] < isolevel) cubeindex |= 8;
    if (grid.val[4] < isolevel) cubeindex |= 16;
    if (grid.val[5] < isolevel) cubeindex |= 32;
    if (grid.val[6] < isolevel) cubeindex |= 64;
    if (grid.val[7] < isolevel) cubeindex |= 128;

    if (edgeTable[cubeindex] == 0) return 0;

    XYZ vertlist[12];

    if (edgeTable[cubeindex] & 1)    vertlist[0]  = VertexInterp(isolevel, grid.p[0], grid.p[1], grid.val[0], grid.val[1]);
    if (edgeTable[cubeindex] & 2)    vertlist[1]  = VertexInterp(isolevel, grid.p[1], grid.p[2], grid.val[1], grid.val[2]);
    if (edgeTable[cubeindex] & 4)    vertlist[2]  = VertexInterp(isolevel, grid.p[2], grid.p[3], grid.val[2], grid.val[3]);
    if (edgeTable[cubeindex] & 8)    vertlist[3]  = VertexInterp(isolevel, grid.p[3], grid.p[0], grid.val[3], grid.val[0]);
    if (edgeTable[cubeindex] & 16)   vertlist[4]  = VertexInterp(isolevel, grid.p[4], grid.p[5], grid.val[4], grid.val[5]);
    if (edgeTable[cubeindex] & 32)   vertlist[5]  = VertexInterp(isolevel, grid.p[5], grid.p[6], grid.val[5], grid.val[6]);
    if (edgeTable[cubeindex] & 64)   vertlist[6]  = VertexInterp(isolevel, grid.p[6], grid.p[7], grid.val[6], grid.val[7]);
    if (edgeTable[cubeindex] & 128)  vertlist[7]  = VertexInterp(isolevel, grid.p[7], grid.p[4], grid.val[7], grid.val[4]);
    if (edgeTable[cubeindex] & 256)  vertlist[8]  = VertexInterp(isolevel, grid.p[0], grid.p[4], grid.val[0], grid.val[4]);
    if (edgeTable[cubeindex] & 512)  vertlist[9]  = VertexInterp(isolevel, grid.p[1], grid.p[5], grid.val[1], grid.val[5]);
    if (edgeTable[cubeindex] & 1024) vertlist[10] = VertexInterp(isolevel, grid.p[2], grid.p[6], grid.val[2], grid.val[6]);
    if (edgeTable[cubeindex] & 2048) vertlist[11] = VertexInterp(isolevel, grid.p[3], grid.p[7], grid.val[3], grid.val[7]);

    int ntriang = 0;

    for (int i = 0; triTable[cubeindex][i] != -1; i += 3) {
        triangles[ntriang].p[0] = vertlist[triTable[cubeindex][i]];
        triangles[ntriang].p[1] = vertlist[triTable[cubeindex][i + 1]];
        triangles[ntriang].p[2] = vertlist[triTable[cubeindex][i + 2]];
        ntriang++;
    }

    return ntriang;
}

void callback() {
    ImGuiIO& io = ImGui::GetIO();

    ImGui::Begin("Selected Triangle / Voxel");

    if (io.MouseClicked[0]) {
        glm::vec2 screenCoords{io.MousePos.x, io.MousePos.y};
        polyscope::PickResult pick = polyscope::pickAtScreenCoords(screenCoords);

        if (pick.structureName == "surface mesh") {
        selectedTri = pick.localIndex / 3;

            if (selectedTri >= 0 && selectedTri < (int)debugTris.size()) {
                const DebugTri& dbg = debugTris[selectedTri];
                const GRIDCELL& c = dbg.cell;

            const TRIANGLE& tri = allTriangles[selectedTri];

            // remove old selected things
            polyscope::removeStructure("selected cube points", false);
            polyscope::removeStructure("selected voxel", false);
            polyscope::removeStructure("selected triangle", false);
            polyscope::removeStructure("triangle intersection points", false);

            //selected cube corner points
            std::vector<std::array<double, 3>> cubePts;
            std::vector<double> cubeVals;

            for (int i = 0; i < 8; ++i) {
                cubePts.push_back({c.p[i].x, c.p[i].y, c.p[i].z});
                cubeVals.push_back(c.val[i]);
            }

            auto* pts = polyscope::registerPointCloud("selected cube points", cubePts);
            pts->addScalarQuantity("corner scalar value", cubeVals)->setEnabled(true);
            pts->setPointRadius(0.0004, true);
            pts->setPointColor({1.0, 0.0, 0.0});

            //selected triangle inside that voxel
            std::vector<std::array<double, 3>> triVerts;
            std::vector<std::array<size_t, 3>> triFaces;

            triVerts.push_back({tri.p[0].x, tri.p[0].y, tri.p[0].z});
            triVerts.push_back({tri.p[1].x, tri.p[1].y, tri.p[1].z});
            triVerts.push_back({tri.p[2].x, tri.p[2].y, tri.p[2].z});

            triFaces.push_back({0, 1, 2});

            auto* selectedMesh = polyscope::registerSurfaceMesh(
                "selected triangle",
                triVerts,
                triFaces
            );

            selectedMesh->setSurfaceColor({1.0, 0.0, 0.0});
            selectedMesh->setSmoothShade(false);
            selectedMesh->setEdgeWidth(2.0);

            //intersection points of triangle
            auto* interPts = polyscope::registerPointCloud(
                "triangle intersection points",
                triVerts
            );

            interPts->setPointRadius(0.0004, true);
            interPts->setPointColor({0.0, 1.0, 0.0});

            //selected voxel wireframe
            glm::vec3 origin{
                (float)c.p[0].x,
                (float)c.p[0].y,
                (float)c.p[0].z
            };

            glm::vec3 cellWidth{
                (float)(c.p[1].x - c.p[0].x),
                (float)(c.p[3].y - c.p[0].y),
                (float)(c.p[4].z - c.p[0].z)
            };

            std::vector<glm::ivec3> oneCell = {{0, 0, 0}};

            auto* vox = polyscope::registerSparseVolumeGrid(
                "selected voxel",
                origin,
                cellWidth,
                oneCell
            );

            vox->setRenderMode(polyscope::SparseVolumeGridRenderMode::Wireframe);
            }
        }
    }

    if (selectedTri != -1 && selectedTri < (int)debugTris.size()) {
        const DebugTri& dbg = debugTris[selectedTri];
        const GRIDCELL& c = dbg.cell;

        ImGui::Text("Triangle index: %d", selectedTri);
        ImGui::Text("Voxel index: ix=%d, iy=%d, iz=%d", dbg.ix, dbg.iy, dbg.iz);

        ImGui::Separator();

        for (int i = 0; i < 8; ++i) {
            ImGui::Text(
                "p%d = (%.3f, %.3f, %.3f), value = %.3f",
                i,
                c.p[i].x, c.p[i].y, c.p[i].z,
                c.val[i]
            );
        }
    }

    ImGui::End();
}

